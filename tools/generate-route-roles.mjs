#!/usr/bin/env node
// tools/generate-route-roles.mjs
//
// Writes supabase/functions/_shared/featureRouteRoles.generated.ts: for every route in src/App.tsx that sits behind
// <RoleGuard allowedRoles={[...]}>, the roles that can really open it.
//
// WHY: the sidebar lists some pages for a role (for example "Gamification" for teachers) whose route guard only lets
// students in; a teacher who clicks it is sent back to the dashboard. An assistant must not explain a page the person
// cannot open (that would describe another role's screen to them), so roleMenuRows() in _shared/roleFeatureGuide.ts
// drops those rows. The edge functions cannot read src/App.tsx, so this file is the bridge, exactly like
// featureManifest.generated.ts is for the sidebar.
//
//   npm run features:generate   rewrite it (also runs before `npm run build`)
//   npm run features:check      exit 1 if it is out of date
//   node tools/generate-route-roles.mjs --report   list pages the sidebar shows to a role but the route blocks
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseRoutes } from "./feature-docs/routes.mjs";
import { parseSidebar } from "./generate-feature-manifest.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const APP = path.join(root, "src/App.tsx");
const SIDEBAR = path.join(root, "src/components/layout/AppSidebar.tsx");
const OUT = path.join(root, "supabase/functions/_shared/featureRouteRoles.generated.ts");

/** { "/gamification": ["student"], ... } for every guarded route, sorted by path. */
export function buildRouteRoles(appSource, appFile = APP, projectRoot = root) {
  const routes = parseRoutes(appSource, appFile, projectRoot);
  const out = {};
  for (const [p, r] of [...routes.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    if (r.allowedRoles && r.allowedRoles.length) out[p] = [...r.allowedRoles].sort();
  }
  return out;
}

export function render(routeRoles) {
  const rows = Object.entries(routeRoles).map(([p, roles]) => `  ${JSON.stringify(p)}: ${JSON.stringify(roles)},`);
  return `// supabase/functions/_shared/featureRouteRoles.generated.ts
//
// GENERATED by tools/generate-route-roles.mjs from src/App.tsx. DO NOT EDIT BY HAND.
// Run \`npm run features:generate\` after changing a route's <RoleGuard allowedRoles>.
// Used by roleFeatureGuide.ts so an assistant never explains a page the route guard would block for that role.

/** Route path -> roles allowed by its <RoleGuard>. Routes with no RoleGuard (any signed-in user) are not listed. */
export const GENERATED_ROUTE_ROLES: Record<string, string[]> = {
${rows.join("\n")}
};
`;
}

/** Sidebar rows a role is shown but the router would turn away. Used by --report and by the tests. */
export function blockedRows(sidebarSource, routeRoles, role) {
  const { rows } = parseSidebar(sidebarSource);
  const out = [];
  const seen = new Set();
  const check = (title, p) => {
    const base = p.split("?")[0];
    const allowed = routeRoles[base];
    if (allowed && !allowed.includes(role) && !seen.has(base)) { seen.add(base); out.push({ title, path: p, allowed }); }
  };
  for (const r of rows) {
    if (!r.roles || !r.roles.includes(role)) continue;
    check(r.title, r.path);
    if (r.subItem) check(r.subItem.title, r.subItem.path);
  }
  return out;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const routeRoles = buildRouteRoles(fs.readFileSync(APP, "utf8"));
  const next = render(routeRoles);
  if (process.argv.includes("--report")) {
    const sidebar = fs.readFileSync(SIDEBAR, "utf8");
    // staff roles only: students and parents are additionally limited by a module allow-list (STUDENT/PARENT_NAV_MODULES)
    for (const role of ["teacher", "hod", "principal", "school_admin"]) {
      const b = blockedRows(sidebar, routeRoles, role);
      console.log(`${role}: ${b.length ? b.map((x) => `${x.title} (${x.path}, route allows: ${x.allowed.join("/")})`).join("; ") : "none"}`);
    }
  } else if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== next) { console.error("featureRouteRoles.generated.ts is out of date. Run: npm run features:generate"); process.exit(1); }
    console.log("featureRouteRoles.generated.ts is up to date.");
  } else {
    fs.writeFileSync(OUT, next);
    console.log(`Wrote ${path.relative(root, OUT)} (${Object.keys(routeRoles).length} guarded routes)`);
  }
}
