#!/usr/bin/env node
// tools/generate-feature-manifest.mjs
//
// Reads the sidebar's menu definition (src/components/layout/AppSidebar.tsx: `navItems`,
// `STUDENT_NAV_MODULES` and `PARENT_NAV_MODULES`) and writes supabase/functions/_shared/featureManifest.generated.ts.
//
// WHY: the Study Buddy (and other assistants) run as Supabase Edge Functions, which cannot import from src/.
// This file is the bridge. Every page added to the sidebar is therefore known to the Study Buddy by name and place
// the next time this runs, without anyone editing an AI prompt. The hand-written how-to text for a feature lives in
// supabase/functions/_shared/studentFeatureGuide.ts and is optional: a menu item with no text is still known.
//
//   npm run features:generate   rewrite the manifest (also runs automatically before `npm run build`)
//   npm run features:check      exit 1 if the manifest is out of date (CI / pre-deploy)
//
// A unit test (src/test/studentFeatureGuide.test.ts) also compares the manifest with the REAL navItems, so a
// change in how the sidebar is written that this parser misreads is caught, not silently ignored.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(root, "src/components/layout/AppSidebar.tsx");
const OUT = path.join(root, "supabase/functions/_shared/featureManifest.generated.ts");

const q = (s) => JSON.stringify(s);
const str = (line, key) => line.match(new RegExp(`\\b${key}:\\s*"([^"]*)"`))?.[1];
const list = (line, key) => {
  const m = line.match(new RegExp(`\\b${key}:\\s*\\[([^\\]]*)\\]`));
  return m ? [...m[1].matchAll(/"([^"]*)"/g)].map((x) => x[1]) : undefined;
};

export function parseSidebar(source) {
  const start = source.indexOf("export const navItems");
  if (start < 0) throw new Error("navItems not found in AppSidebar.tsx");
  const end = source.indexOf("\n];", start);
  const rows = [];
  for (const raw of source.slice(start, end).split("\n")) {
    const line = raw.trim();
    if (!line.startsWith("{") || !line.includes("path:")) continue; // comments, blank lines, the array opener
    const row = { title: str(line, "title"), path: str(line, "path") };
    if (!row.title || !row.path) continue;
    const roles = list(line, "roles");
    const studentTitle = str(line, "studentTitle");
    const mod = str(line, "module");
    const sub = line.match(/subItem:\s*\{\s*title:\s*"([^"]*)"[^}]*?path:\s*"([^"]*)"/);
    if (roles) row.roles = roles;
    if (studentTitle) row.studentTitle = studentTitle;
    if (mod) row.module = mod;
    if (sub) row.subItem = { title: sub[1], path: sub[2] };
    rows.push(row);
  }
  const modulesOf = (name) => {
    const m = source.match(new RegExp(`export const ${name}\\s*=\\s*\\[([^\\]]*)\\]`));
    if (!m) throw new Error(`${name} not found in AppSidebar.tsx`);
    return [...m[1].matchAll(/"([^"]*)"/g)].map((x) => x[1]);
  };
  const studentModules = modulesOf("STUDENT_NAV_MODULES");
  const parentModules = modulesOf("PARENT_NAV_MODULES");
  if (rows.length < 10 || studentModules.length < 5 || parentModules.length < 3) throw new Error("Sidebar parse looks wrong - refusing to write the manifest");
  return { rows, studentModules, parentModules };
}

export function render({ rows, studentModules, parentModules }) {
  const row = (r) => {
    const parts = [`title: ${q(r.title)}`, `path: ${q(r.path)}`];
    if (r.studentTitle) parts.push(`studentTitle: ${q(r.studentTitle)}`);
    if (r.roles) parts.push(`roles: ${q(r.roles)}`);
    if (r.module) parts.push(`module: ${q(r.module)}`);
    if (r.subItem) parts.push(`subItem: { title: ${q(r.subItem.title)}, path: ${q(r.subItem.path)} }`);
    return `  { ${parts.join(", ")} },`;
  };
  return `// supabase/functions/_shared/featureManifest.generated.ts
//
// GENERATED by tools/generate-feature-manifest.mjs from src/components/layout/AppSidebar.tsx. DO NOT EDIT BY HAND.
// Run \`npm run features:generate\` after changing the sidebar (it also runs before \`npm run build\`).
// Used by studentFeatureGuide.ts and parentFeatureGuide.ts so the assistants know every menu page without anyone editing a prompt.

export interface GeneratedNavRow {
  title: string;
  path: string;
  studentTitle?: string;
  roles?: string[];
  module?: string;
  subItem?: { title: string; path: string };
}

/** Every sidebar row, in menu order, for every role. */
export const GENERATED_NAV: GeneratedNavRow[] = [
${rows.map(row).join("\n")}
];

/** The modules a student's menu is allowed to show (STUDENT_NAV_MODULES in AppSidebar.tsx). */
export const GENERATED_STUDENT_MODULES: string[] = ${q(studentModules)};

/** The modules a parent's menu is allowed to show (PARENT_NAV_MODULES in AppSidebar.tsx). */
export const GENERATED_PARENT_MODULES: string[] = ${q(parentModules)};
`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const next = render(parseSidebar(fs.readFileSync(SRC, "utf8")));
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== next) {
      console.error("featureManifest.generated.ts is out of date. Run: npm run features:generate");
      process.exit(1);
    }
    console.log("featureManifest.generated.ts is up to date.");
  } else {
    fs.writeFileSync(OUT, next);
    console.log(`Wrote ${path.relative(root, OUT)}`);
  }
}
